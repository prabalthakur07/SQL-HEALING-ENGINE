/**
 * Runs the full benchmark suite through the self-healing loop and produces
 * a markdown report with the REAL, measured success rate + healing stats.
 *
 * This is what your resume bullet's percentage should come from - run it,
 * paste the actual number, don't guess.
 *
 * Usage: npm run benchmark
 */
import fs from 'fs';
import path from 'path';
import { runHealingLoop } from '../lib/healingEngine';

interface BenchmarkCase {
  id: number;
  question: string;
  expectMinRows?: number;
  expectMaxRows?: number;
}

async function main() {
  const casesPath = path.join(process.cwd(), 'data', 'benchmark-queries.json');
  const cases: BenchmarkCase[] = JSON.parse(fs.readFileSync(casesPath, 'utf-8'));

  let executionSuccesses = 0; // query ran without error at all
  let firstTrySuccesses = 0; // succeeded with zero healing needed
  let healedSuccesses = 0; // succeeded only after >=1 retry
  let totalAttemptsAcrossAll = 0;
  const rows: string[] = [];

  console.log(`Running ${cases.length} benchmark queries...\n`);

  for (const c of cases) {
    process.stdout.write(`  #${c.id} "${c.question}" ... `);
    const result = await runHealingLoop(c.question, false);
    totalAttemptsAcrossAll += result.attempts.length;

    let rowCountOk = true;
    if (result.success && result.rowCount !== undefined) {
      if (c.expectMinRows !== undefined && result.rowCount < c.expectMinRows) rowCountOk = false;
      if (c.expectMaxRows !== undefined && result.rowCount > c.expectMaxRows) rowCountOk = false;
    }

    const passed = result.success && rowCountOk;
    if (passed) {
      executionSuccesses++;
      if (result.attempts.length === 1) firstTrySuccesses++;
      else healedSuccesses++;
    }

    console.log(passed ? `✅ (${result.attempts.length} attempt${result.attempts.length > 1 ? 's' : ''})` : '❌');

    rows.push(
      `| ${c.id} | ${c.question} | ${passed ? '✅' : '❌'} | ${result.attempts.length} | ${
        result.success ? result.rowCount : '—'
      } |`
    );
  }

  const successRate = ((executionSuccesses / cases.length) * 100).toFixed(1);
  const avgAttempts = (totalAttemptsAcrossAll / cases.length).toFixed(2);

  const report = `# Benchmark Report

Generated: ${new Date().toISOString()}

## Summary

- **Total queries:** ${cases.length}
- **Overall success rate:** ${successRate}%
- **Succeeded on first try (no healing needed):** ${firstTrySuccesses}
- **Succeeded only after self-healing (1+ retries):** ${healedSuccesses}
- **Failed after max attempts:** ${cases.length - executionSuccesses}
- **Average attempts per query:** ${avgAttempts}

## Per-query results

| ID | Question | Result | Attempts | Rows |
|----|----------|--------|----------|------|
${rows.join('\n')}

---
*This report is generated by \`npm run benchmark\`. Re-run any time the schema, prompt,
or model changes to get an up-to-date, honest success-rate number for your resume/portfolio.*
`;

  fs.writeFileSync(path.join(process.cwd(), 'benchmark-report.md'), report);
  console.log(`\nSuccess rate: ${successRate}% — full report written to benchmark-report.md`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
